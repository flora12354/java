// 所有分类（用于首页筛选条）
export const allTags = ['全部', ...new Set(mockGoods.map(i => i.tag))]

// 根据名称或分类过滤
export function filterGoods(kw, tag = '全部') {
  let list = mockGoods
  if (tag && tag !== '全部') list = list.filter(i => i.tag === tag)
  if (!kw) return list
  return list.filter(i => i.name.includes(kw) || i.tag.includes(kw))
}

// 根据 id 查找商品
export function findGoodsById(id) {
  return mockGoods.find(i => String(i.id) === String(id))
}
